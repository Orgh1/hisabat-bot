const { parseMessage } = require('../src/parser');
const config = require('../src/config.example.json');

let passed = 0;
const failures = [];

function one(text) {
  const r = parseMessage(text, config).lines;
  if (r.length !== 1) throw new Error(`expected 1 line, got ${r.length}`);
  return r[0];
}

function check(name, fn) {
  try {
    fn();
    passed++;
    console.log(`  ✓ ${name}`);
  } catch (e) {
    failures.push(name);
    console.log(`  ✗ ${name} — ${e.message}`);
  }
}

function eq(actual, expected, label) {
  if (actual !== expected) throw new Error(`${label}: got ${JSON.stringify(actual)}, want ${JSON.stringify(expected)}`);
}

